import { createHash } from 'node:crypto';
import { readFile, writeFile, readdir, mkdir, lstat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { iconPng } from '../pwa/icon-png.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MIME = new Map([
  ['.html', 'text/html; charset=utf-8'], ['.js', 'text/javascript; charset=utf-8'],
  ['.css', 'text/css; charset=utf-8'], ['.json', 'application/json; charset=utf-8'],
  ['.webmanifest', 'application/manifest+json'], ['.svg', 'image/svg+xml'],
  ['.png', 'image/png'], ['.jpg', 'image/jpeg'], ['.jpeg', 'image/jpeg'], ['.webp', 'image/webp'],
  ['.hdr', 'image/vnd.radiance'], ['.woff', 'font/woff'], ['.woff2', 'font/woff2'],
  ['.wav', 'audio/wav'], ['.mp3', 'audio/mpeg'], ['.ogg', 'audio/ogg'],
]);
export const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
async function runtimeFiles(root, directory) {
  const files = [];
  for (const entry of await readdir(path.join(root, directory), { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const relative = `${directory}/${entry.name}`;
    if (entry.isSymbolicLink()) throw new Error(`Release inputs cannot be symbolic links: ${relative}`);
    if (entry.isDirectory()) files.push(...await runtimeFiles(root, relative));
    else if ((directory === 'src' && ['.js', '.css'].includes(path.extname(entry.name))) || (directory.startsWith('assets') && MIME.has(path.extname(entry.name))) || (directory.startsWith('vendor') && (path.extname(entry.name) === '.js' || entry.name === 'LICENSE'))) {
      if (relative !== 'src/build-info.js') files.push(relative);
    }
  }
  return files;
}

export async function buildMobileRelease({ root = ROOT, outputRoot = path.join(root, 'artifacts', 'mobile-release') } = {}) {
  const files = new Map();
  for (const directory of ['src', 'vendor', 'assets']) {
    if ((await lstat(path.join(root, directory))).isSymbolicLink()) throw new Error(`Release input cannot be a symbolic link: ${directory}`);
    for (const relative of await runtimeFiles(root, directory)) files.set(`/${relative}`, await readFile(path.join(root, relative)));
  }
  let html = await readFile(path.join(root, 'index.html'), 'utf8');
  if (!html.includes('</head>')) throw new Error('index.html must contain a closing head tag.');
  html = html.replace('</head>', `  <link rel="manifest" href="/manifest.webmanifest" />\n  <link rel="apple-touch-icon" href="/icons/apple-touch-icon.png" />\n  <meta name="apple-mobile-web-app-capable" content="yes" />\n  <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />\n  <meta name="apple-mobile-web-app-title" content="Colossus Wake" />\n</head>`);
  files.set('/index.html', Buffer.from(html));
  files.set('/manifest.webmanifest', await readFile(path.join(root, 'pwa', 'manifest.webmanifest')));
  const svg = (await readFile(path.join(root, 'assets', 'icon.svg'))).toString();
  for (const [size, name] of [[180, 'apple-touch-icon'], [192, 'icon-192'], [512, 'icon-512']]) files.set(`/icons/${name}.png`, iconPng(svg, size));
  const workerTemplate = await readFile(path.join(root, 'pwa', 'service-worker.js'), 'utf8');
  const identity = [...files].map(([url, bytes]) => ({ url, sha256: sha256(bytes) })).sort((a, b) => a.url.localeCompare(b.url));
  // The generated build-info is excluded to avoid a recursive hash. All shipped
  // runtime bytes, metadata, icons, and worker behavior contribute to the ID.
  const buildId = sha256(JSON.stringify({ files: identity, worker: sha256(workerTemplate) })).slice(0, 20);
  const buildInfo = Buffer.from(`// Generated by scripts/build-mobile-release.mjs. Rebuild after runtime changes.\nexport const BUILD_ID = '${buildId}';\n`);
  files.set('/src/build-info.js', buildInfo);
  const manifest = [...files].map(([url, bytes]) => ({ url, bytes: bytes.length, sha256: sha256(bytes), type: MIME.get(path.extname(url)) || 'text/plain; charset=utf-8' })).sort((a, b) => a.url.localeCompare(b.url));
  const release = { app: 'colossus-wake', schemaVersion: 1, buildId, files: manifest, totalBytes: manifest.reduce((sum, file) => sum + file.bytes, 0) };
  const worker = workerTemplate.replace('__RELEASE_DESCRIPTOR__', JSON.stringify(release));
  files.set('/sw.js', Buffer.from(worker));
  files.set('/release.json', Buffer.from(JSON.stringify(release, null, 2) + '\n'));
  const output = path.join(outputRoot, buildId);
  await mkdir(output, { recursive: true });
  // A content-addressed release directory may be rebuilt only if it has no
  // unexpected files. Refuse contamination instead of deleting user files.
  async function checkOutput(directory, prefix = '') {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const relative = `${prefix}/${entry.name}`;
      if (entry.isSymbolicLink()) throw new Error(`Unexpected release symlink: ${relative}`);
      if (entry.isDirectory()) await checkOutput(path.join(directory, entry.name), relative);
      else if (!files.has(relative)) throw new Error(`Unexpected file in release output: ${relative}`);
    }
  }
  await checkOutput(output);
  for (const [url, bytes] of files) {
    const destination = path.join(output, url.slice(1));
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, bytes);
  }
  // Write the same identity into the PC source only after the release is complete.
  await writeFile(path.join(root, 'src', 'build-info.js'), buildInfo);
  return { buildId, output, fileCount: files.size, precacheCount: manifest.length, totalBytes: release.totalBytes };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await buildMobileRelease(), null, 2));
}
